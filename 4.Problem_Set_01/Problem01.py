"""
Take two numbers as input from the user. Print their sum, difference,
product, and remainder.

"""

num1 = int(input("Enter 1st Number: "))
num2 = int(input("Enter 2st Number: "))

# calculating and printing sum 
print(f"Sum of {num1} and {num2} : {num1+num2}")
# Calculating and printing Difference 
print(f"Difference of {num1} nad {num2}: {num1 - num2}")
# Calculating and Printing Product
print(f"Product of{num1} and {num2}: {num1 * num2}")
# Calculating and Printing Remainder
print(f"Remainder of {num1} and {num2}: {num1 % num2}")