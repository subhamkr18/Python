# AND, OR, NOT

chemistry = 45
physics = 34 

# logical operators also gives output in True or False

# AND - All given condition should be true then it will give true

print(chemistry>33 and physics > 33)

# OR- gives True if any given condition is true Flase if all given contion is false

print(chemistry>33 or physics>33)

# Not- It reverse the result 
print(not chemistry > 33 and not physics>33)