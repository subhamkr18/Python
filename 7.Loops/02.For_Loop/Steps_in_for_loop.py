# default step 1
for i in range(1,11):
    print(i,end=" ")

print("\nUsing Step as 2 ")
# step 2
for i in range(1,11,2):
    print(i,end=" ")

print("\nUsing Step 3")
# step 4
for i in range(1,11,4):
    print(i,end=" ")